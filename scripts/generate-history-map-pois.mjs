#!/usr/bin/env node

import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import process from 'node:process'
import { format, resolveConfig } from 'prettier'

const SOURCE_NAME = /^BY_Digital_Map_layer4_(\d{2})\.svg$/i

const HELP = `Usage:
  node scripts/generate-history-map-pois.mjs \\
    --input <svg-directory> \\
    --output <positions.ts>

The generator reads the normal, numbered layer 4 POI SVGs. Each source must
contain two concentric circles in the shared map viewBox. Selected (_ins),
preview, border, and other SVG files are ignored.
`

function parseArguments(argv) {
  if (argv.includes('--help') || argv.includes('-h')) {
    process.stdout.write(HELP)
    process.exit(0)
  }

  const options = {}

  for (let index = 0; index < argv.length; index += 2) {
    const flag = argv[index]
    const value = argv[index + 1]

    if (!flag?.startsWith('--') || value === undefined) {
      throw new Error(`Invalid argument near "${flag ?? ''}".\n\n${HELP}`)
    }

    options[flag.slice(2)] = value
  }

  if (!options.input || !options.output) {
    throw new Error(`--input and --output are required.\n\n${HELP}`)
  }

  return {
    input: resolve(options.input),
    output: resolve(options.output)
  }
}

function attributes(element) {
  return Object.fromEntries(
    [...element.matchAll(/([\w:-]+)=(?:"([^"]*)"|'([^']*)')/g)].map(match => [
      match[1],
      match[2] ?? match[3]
    ])
  )
}

function finiteNumber(value, attribute, sourceName) {
  const number = Number(value)

  if (!Number.isFinite(number)) {
    throw new Error(
      `Expected a numeric ${attribute} attribute in "${sourceName}".`
    )
  }

  return number
}

function extractViewBox(svg, sourceName) {
  const svgElement = svg.match(/<svg\b[^>]*>/i)?.[0]

  if (!svgElement) {
    throw new Error(`Cannot find the root <svg> in "${sourceName}".`)
  }

  const viewBox = attributes(svgElement)
    .viewBox?.trim()
    .split(/[\s,]+/)
    .map(value => Number(value))

  if (
    !viewBox ||
    viewBox.length !== 4 ||
    viewBox.some(value => !Number.isFinite(value)) ||
    viewBox[2] <= 0 ||
    viewBox[3] <= 0
  ) {
    throw new Error(`Expected a valid viewBox in "${sourceName}".`)
  }

  return viewBox
}

function extractCenter(svg, sourceName) {
  const circles = [...svg.matchAll(/<circle\b[^>]*\/?\s*>/gi)].map(match =>
    attributes(match[0])
  )

  if (circles.length !== 2) {
    throw new Error(
      `Expected exactly two marker circles in "${sourceName}", found ${circles.length}.`
    )
  }

  const centers = circles.map(circle => [
    finiteNumber(circle.cx, 'cx', sourceName),
    finiteNumber(circle.cy, 'cy', sourceName)
  ])

  if (centers[0][0] !== centers[1][0] || centers[0][1] !== centers[1][1]) {
    throw new Error(`Marker circles are not concentric in "${sourceName}".`)
  }

  return centers[0]
}

function sameViewBox(left, right) {
  return left.every((value, index) => value === right[index])
}

async function main() {
  const options = parseArguments(process.argv.slice(2))
  const entries = await readdir(options.input, { withFileTypes: true })
  const sources = entries
    .filter(entry => entry.isFile())
    .map(entry => {
      const match = entry.name.match(SOURCE_NAME)
      return match ? { id: match[1], name: entry.name } : null
    })
    .filter(Boolean)
    .sort((left, right) => left.id.localeCompare(right.id, 'en'))

  if (sources.length === 0) {
    throw new Error(`No normal layer 4 POI SVGs found in ${options.input}`)
  }

  const positions = []
  let sharedViewBox

  for (const [index, source] of sources.entries()) {
    const expectedId = String(index + 1).padStart(2, '0')

    if (source.id !== expectedId) {
      throw new Error(
        `Expected POI ${expectedId}, found ${source.id} in "${source.name}".`
      )
    }

    const svg = await readFile(resolve(options.input, source.name), 'utf8')
    const viewBox = extractViewBox(svg, source.name)

    if (sharedViewBox && !sameViewBox(sharedViewBox, viewBox)) {
      throw new Error(
        `Expected "${source.name}" to use the shared viewBox ${sharedViewBox.join(' ')}.`
      )
    }

    sharedViewBox ??= viewBox
    positions.push({ id: source.id, center: extractCenter(svg, source.name) })
  }

  const [minX, minY, width, height] = sharedViewBox
  const prettierOptions = (await resolveConfig(resolve('package.json'))) ?? {}
  const generated = await format(
    `/**
     * Generated by scripts/generate-history-map-pois.mjs.
     * Do not edit; update the normal layer 4 POI SVGs and regenerate.
     */

    export type HistoryMapPoiPosition = {
      id: string
      center: readonly [x: number, y: number]
    }

    export const LAYER_FOUR_POI_VIEW_BOX = {
      minX: ${minX},
      minY: ${minY},
      width: ${width},
      height: ${height}
    } as const

    export const LAYER_FOUR_POI_POSITIONS = ${JSON.stringify(
      positions
    )} as const satisfies readonly HistoryMapPoiPosition[]
    `,
    { ...prettierOptions, filepath: options.output }
  )

  await mkdir(dirname(options.output), { recursive: true })
  await writeFile(options.output, generated)
  process.stdout.write(
    `Generated ${positions.length} POI positions in ${options.output}\n`
  )
}

main().catch(error => {
  process.stderr.write(
    `${error instanceof Error ? error.message : String(error)}\n`
  )
  process.exitCode = 1
})
